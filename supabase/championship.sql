-- Инициализация сезонной статистики всех игроков клуба (нули)
create or replace function public.init_championship_season_stats(
  p_championship_id bigint,
  p_home_team_id bigint
)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.championship_player_season_stats (
    championship_id, player_id, team_id,
    matches_played, goals, assists, mvp_count, rating_sum, rating_count
  )
  select
    p_championship_id,
    p.id,
    p_home_team_id,
    0, 0, 0, 0, 0, 0
  from public.players p
  on conflict (championship_id, player_id) do nothing;
end;
$$;

