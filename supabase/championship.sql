-- Чемпионат: отдельный сезон, отдельные сущности, без смешивания с карьерой.
-- Supabase → SQL Editor → Run

-- 1) Сезоны чемпионата
create table if not exists public.championships (
  id bigint generated by default as identity primary key,
  name text not null,
  season text not null,
  starts_at date,
  ends_at date,
  status text not null default 'active'
    check (status in ('draft', 'active', 'finished')),
  created_at timestamptz not null default now()
);

create unique index if not exists championships_season_uidx
  on public.championships (season);

-- 2) Команды (переиспользуются между сезонами)
create table if not exists public.championship_teams (
  id bigint generated by default as identity primary key,
  name text not null,
  logo_url text,
  primary_color text not null default '#fbbf24',
  secondary_color text not null default '#78350f',
  created_at timestamptz not null default now(),
  unique (name)
);

-- 3) Участники сезона
create table if not exists public.championship_participants (
  championship_id bigint not null
    references public.championships (id) on delete cascade,
  team_id bigint not null
    references public.championship_teams (id) on delete cascade,
  primary key (championship_id, team_id)
);

-- 4) Матчи чемпионата (не таблица matches клуба)
create table if not exists public.championship_matches (
  id bigint generated by default as identity primary key,
  championship_id bigint not null
    references public.championships (id) on delete cascade,
  home_team_id bigint not null
    references public.championship_teams (id),
  away_team_id bigint not null
    references public.championship_teams (id),
  match_date date not null,
  match_time text not null default '18:00',
  location text not null default '',
  home_goals integer,
  away_goals integer,
  is_played boolean not null default false,
  is_live boolean not null default false,
  created_at timestamptz not null default now(),
  check (home_team_id <> away_team_id)
);

create index if not exists championship_matches_champ_idx
  on public.championship_matches (championship_id, match_date desc, id desc);

-- 5) События матча чемпионата (голы/пассы/MVP сезона)
create table if not exists public.championship_match_player_stats (
  id bigint generated by default as identity primary key,
  match_id bigint not null
    references public.championship_matches (id) on delete cascade,
  player_id bigint not null
    references public.players (id) on delete cascade,
  team_id bigint not null
    references public.championship_teams (id),
  goals integer not null default 0,
  assists integer not null default 0,
  is_mvp boolean not null default false,
  match_rating numeric(4, 1),
  unique (match_id, player_id)
);

create index if not exists championship_match_player_stats_player_idx
  on public.championship_match_player_stats (player_id);

-- 6) Сезонная статистика игрока (обнуляется с новым чемпионатом)
create table if not exists public.championship_player_season_stats (
  id bigint generated by default as identity primary key,
  championship_id bigint not null
    references public.championships (id) on delete cascade,
  player_id bigint not null
    references public.players (id) on delete cascade,
  team_id bigint not null
    references public.championship_teams (id),
  matches_played integer not null default 0,
  goals integer not null default 0,
  assists integer not null default 0,
  mvp_count integer not null default 0,
  rating_sum numeric(10, 2) not null default 0,
  rating_count integer not null default 0,
  unique (championship_id, player_id)
);

create index if not exists championship_player_season_stats_champ_idx
  on public.championship_player_season_stats (championship_id);

