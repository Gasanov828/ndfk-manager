on conflict (name) do nothing;

insert into public.championships (name, season, starts_at, status)
select 'ДоргеЛига', '2026', current_date, 'active'
where not exists (
  select 1 from public.championships where season = '2026'
);

update public.championships
set name = 'ДоргеЛига'
where season = '2026';

insert into public.championship_participants (championship_id, team_id)
select c.id, t.id
from public.championships c
cross join public.championship_teams t
where c.season = '2026'
  and t.name in (
    'Дженгутай',
    'Доргели',
    'Бирлик (Доргели)',
    'Какашура',
    'Казанище',
    'Какашура 2'
  )
on conflict do nothing;

do $$
declare
  v_champ_id bigint;
  v_home_id bigint;
begin
  select id into v_champ_id from public.championships where season = '2026' limit 1;
  select id into v_home_id from public.championship_teams where name = 'Дженгутай' limit 1;
  if v_champ_id is not null and v_home_id is not null then
    perform public.init_championship_season_stats(v_champ_id, v_home_id);
  end if;
end $$;
