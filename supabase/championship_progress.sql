-- Инициализация прогресса всех игроков клуба на новый сезон
create or replace function public.init_championship_player_progress(
  p_championship_id bigint,
  p_home_team_id bigint
)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.championship_player_progress (
    championship_id, player_id, team_id,
    season_xp, season_level, season_rating,
    season_cards, season_rewards, rating_sum, rating_count
  )
  select
    p_championship_id,
    p.id,
    p_home_team_id,
    0, 1, 0,
    0, 0, 0, 0
  from public.players p
  on conflict (championship_id, player_id) do nothing;
end;
$$;

-- Расширяем init статистики: также прогресс
create or replace function public.init_championship_season_stats(
  p_championship_id bigint,
  p_home_team_id bigint
)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.championship_player_season_stats (
    championship_id, player_id, team_id,
    matches_played, goals, assists, mvp_count, rating_sum, rating_count
  )
  select
    p_championship_id,
    p.id,
    p_home_team_id,
    0, 0, 0, 0, 0, 0
  from public.players p
  on conflict (championship_id, player_id) do nothing;

  perform public.init_championship_player_progress(p_championship_id, p_home_team_id);
end;
$$;

-- Инициализация для активного сезона
do $$
declare
  v_champ_id bigint;
  v_home_id bigint;
begin
  select id into v_champ_id
  from public.championships
  where status = 'active'
  order by id desc
  limit 1;
  select id into v_home_id
  from public.championship_teams
  where name = 'Дженгутай'
  limit 1;
  if v_champ_id is not null and v_home_id is not null then
    perform public.init_championship_player_progress(v_champ_id, v_home_id);
  end if;
end $$;
