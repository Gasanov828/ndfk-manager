-- Прогресс сезона чемпионата (отдельно от карьеры)
-- Supabase → SQL Editor → Run после championship.sql

-- Туры сезона
create table if not exists public.championship_rounds (
  id bigint generated by default as identity primary key,
  championship_id bigint not null
    references public.championships (id) on delete cascade,
  round_number integer not null,
  title text,
  status text not null default 'upcoming'
    check (status in ('upcoming', 'active', 'finished')),
  results_applied_at timestamptz,
  created_at timestamptz not null default now(),
  unique (championship_id, round_number)
);

create index if not exists championship_rounds_champ_idx
  on public.championship_rounds (championship_id, round_number);

-- Привязка матча к туру
alter table public.championship_matches
  add column if not exists round_id bigint
    references public.championship_rounds (id) on delete set null;

alter table public.championship_matches
  add column if not exists tour_results_applied boolean not null default false;

-- Прогресс игрока в чемпионате (сбрасывается с новым сезоном — новая строка на championship_id)
create table if not exists public.championship_player_progress (
  id bigint generated by default as identity primary key,
  championship_id bigint not null
    references public.championships (id) on delete cascade,
  player_id bigint not null
    references public.players (id) on delete cascade,
  team_id bigint not null
    references public.championship_teams (id),
  season_xp integer not null default 0,
  season_level integer not null default 1,
  season_rating numeric(4, 1) not null default 0,
  season_cards integer not null default 0,
  season_rewards integer not null default 0,
  rating_sum numeric(10, 2) not null default 0,
  rating_count integer not null default 0,
  updated_at timestamptz not null default now(),
  unique (championship_id, player_id)
);

create index if not exists championship_player_progress_champ_idx
  on public.championship_player_progress (championship_id, season_xp desc);

-- Карточки сезона (архитектура; содержимое позже)
create table if not exists public.championship_season_cards (
  id bigint generated by default as identity primary key,
  championship_id bigint not null
    references public.championships (id) on delete cascade,
  player_id bigint not null
    references public.players (id) on delete cascade,
  card_code text not null,
  card_title text not null default '',
  rarity text not null default 'common',
  earned_at timestamptz not null default now(),
  meta jsonb not null default '{}'::jsonb
);

create index if not exists championship_season_cards_player_idx
  on public.championship_season_cards (championship_id, player_id);

-- Награды сезона (архитектура; содержимое позже)
create table if not exists public.championship_season_rewards (
  id bigint generated by default as identity primary key,
  championship_id bigint not null
    references public.championships (id) on delete cascade,
  player_id bigint
    references public.players (id) on delete set null,
  team_id bigint
    references public.championship_teams (id) on delete set null,
  reward_code text not null,
  reward_title text not null default '',
  earned_at timestamptz not null default now(),
  meta jsonb not null default '{}'::jsonb
);

create index if not exists championship_season_rewards_champ_idx
  on public.championship_season_rewards (championship_id);

-- Лог начисления XP за матч (идемпотентность итогов тура)
create table if not exists public.championship_match_xp_log (
  id bigint generated by default as identity primary key,
  match_id bigint not null
    references public.championship_matches (id) on delete cascade,
  player_id bigint not null
    references public.players (id) on delete cascade,
  match_rating numeric(4, 1),
  xp_gained integer not null default 0,
  level_before integer not null default 1,
  level_after integer not null default 1,
  created_at timestamptz not null default now(),
  unique (match_id, player_id)
);

